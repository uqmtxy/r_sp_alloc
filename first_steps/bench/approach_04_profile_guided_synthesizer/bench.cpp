namespace {

// Workload distribution corresponding to empirical profile
const std::vector<size_t> SIZES = {
    24, 32, 48, 72, 96, 128, 160, 216, 288, 384, 512, 640, 800, 1024, 1280, 1536, 2048
};
const std::vector<double> WEIGHTS = {
    15.0, 25.0, 8.0, 45.0, 12.0, 18.0, 5.0, 22.0, 30.0, 7.0, 14.0, 4.0, 11.0, 9.0, 2.0, 6.0, 4.0
};

// Generic Power-of-Two Size Classes (7 bins)
const std::vector<size_t> POW2_CLASSES = {32, 64, 128, 256, 512, 1024, 2048};

// Quantum Size Classes (19 bins)
const std::vector<size_t> QUANTUM_CLASSES = {
    32, 48, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 384, 512, 640, 800, 1024, 1536, 2048
};

// PGO Synthesized Classes (Generated by dynamic programming optimizer: 8 bins)
const std::vector<size_t>& PGO_CLASSES = pgo_alloc::OPTIMAL_SIZE_CLASSES;

struct BenchConfig {
    size_t live_objects = 200000;
    size_t churn_ops = 1000000;
    int trials = 5;
    uint64_t seed = 0x512E42;
    int cpu_pin = 0;
};

struct TrialResult {
    double mops_per_sec = 0.0;
    double ns_per_op = 0.0;
    long peak_rss_kb = 0;
    double internal_frag_pct = 0.0;
    size_t total_bins = 0;
};

struct StatsSummary {
    double median_mops = 0.0;
    double stddev_mops = 0.0;
    double median_ns_op = 0.0;
    long median_rss_kb = 0;
    double internal_frag_pct = 0.0;
    size_t total_bins = 0;
};

long get_peak_rss_kb() {
#if defined(__linux__)
    std::ifstream status("/proc/self/status");
    std::string line;
    while (std::getline(status, line)) {
        if (line.rfind("VmHWM:", 0) == 0) {
            long val = 0;
            std::sscanf(line.c_str(), "VmHWM: %ld kB", &val);
            return val;
        }
    }
    struct rusage usage;
    if (getrusage(RUSAGE_SELF, &usage) == 0) return usage.ru_maxrss;
#endif
    return 0;
}

void pin_to_core(int core_id) {
#if defined(__linux__)
    cpu_set_t cpuset;
    CPU_ZERO(&cpuset);
    CPU_SET(core_id, &cpuset);
    pthread_setaffinity_np(pthread_self(), sizeof(cpu_set_t), &cpuset);
#endif
}

struct AllocItem {
    void* ptr = nullptr;
    size_t size = 0;
    int bin_index = -1;
};

TrialResult run_trial(const std::string& mode, const BenchConfig& cfg) {
    std::mt19937_64 rng(cfg.seed);
    std::discrete_distribution<size_t> dist(WEIGHTS.begin(), WEIGHTS.end());
    std::uniform_int_distribution<size_t> slot_dist(0, cfg.live_objects - 1);

    slab_bench::MultiSlabAllocator* slab = nullptr;
    size_t bin_count = 0;

    if (mode == "pow2") {
        slab = new slab_bench::MultiSlabAllocator(POW2_CLASSES);
        bin_count = POW2_CLASSES.size();
    } else if (mode == "quantum") {
        slab = new slab_bench::MultiSlabAllocator(QUANTUM_CLASSES);
        bin_count = QUANTUM_CLASSES.size();
    } else if (mode == "pgo_synthesized") {
        slab = new slab_bench::MultiSlabAllocator(PGO_CLASSES);
        bin_count = PGO_CLASSES.size();
    }

    std::vector<AllocItem> live(cfg.live_objects);
    size_t total_payload = 0;
    size_t total_effective = 0;

    auto do_alloc = [&](size_t size, int& bin_idx) -> void* {
        if (slab) {
            return slab->allocate(size, bin_idx);
        } else {
            bin_idx = -1;
            return std::malloc(size);
        }
    };

    auto do_free = [&](void* ptr, int bin_idx) {
        if (slab) {
            slab->deallocate(ptr, bin_idx);
        } else {
            std::free(ptr);
        }
    };

    // Populate live set
    for (size_t i = 0; i < cfg.live_objects; ++i) {
        size_t s = SIZES[dist(rng)];
        int b = -1;
        void* p = do_alloc(s, b);
        *reinterpret_cast<uint64_t*>(p) = 0x12345678ULL;
        live[i] = {p, s, b};
        total_payload += s;

        // Compute effective bin size
        if (slab && b >= 0) {
            total_effective += slab->sizes()[b];
        } else {
            total_effective += (s + 15) & ~size_t(15);
        }
    }

    // Churn loop
    auto t0 = std::chrono::high_resolution_clock::now();
    for (size_t op = 0; op < cfg.churn_ops; ++op) {
        size_t slot = slot_dist(rng);
        do_free(live[slot].ptr, live[slot].bin_index);

        size_t new_size = SIZES[dist(rng)];
        int new_b = -1;
        void* p = do_alloc(new_size, new_b);
        *reinterpret_cast<uint64_t*>(p) = 0x87654321ULL;
        live[slot] = {p, new_size, new_b};
    }
    auto t1 = std::chrono::high_resolution_clock::now();
    double sec = std::chrono::duration<double>(t1 - t0).count();

    long peak_rss = get_peak_rss_kb();

    // Cleanup
    for (size_t i = 0; i < cfg.live_objects; ++i) {
        do_free(live[i].ptr, live[i].bin_index);
    }
    delete slab;

    TrialResult res;
    res.mops_per_sec = (static_cast<double>(cfg.churn_ops) / sec) / 1e6;
    res.ns_per_op = (sec / static_cast<double>(cfg.churn_ops)) * 1e9;
    res.peak_rss_kb = peak_rss;
    res.total_bins = bin_count;
    if (total_effective > total_payload) {
        res.internal_frag_pct = 100.0 * (1.0 - (static_cast<double>(total_payload) / total_effective));
    }
    return res;
}

StatsSummary compute_stats(std::vector<TrialResult>& trials) {
    std::sort(trials.begin(), trials.end(), [](const TrialResult& a, const TrialResult& b) {
        return a.mops_per_sec < b.mops_per_sec;
    });
    size_t n = trials.size();
    StatsSummary s;
    s.median_mops = trials[n / 2].mops_per_sec;
    s.median_ns_op = trials[n / 2].ns_per_op;
    s.median_rss_kb = trials[n / 2].peak_rss_kb;
    s.internal_frag_pct = trials[n / 2].internal_frag_pct;
    s.total_bins = trials[n / 2].total_bins;

    double sum = 0.0;
    for (const auto& t : trials) sum += t.mops_per_sec;
    double mean = sum / n;
    double sq = 0.0;
    for (const auto& t : trials) {
        double d = t.mops_per_sec - mean;
        sq += d * d;
    }
    s.stddev_mops = std::sqrt(sq / n);
    return s;
}

} // namespace

int main(int argc, char** argv) {
    std::string mode = "pgo_synthesized";
    if (argc > 1) mode = argv[1];

    BenchConfig cfg;
    pin_to_core(cfg.cpu_pin);

    // Warmup
    run_trial(mode, cfg);

    std::vector<TrialResult> trials;
    for (int t = 0; t < cfg.trials; ++t) {
        cfg.seed = 0x512E42 + t * 10007;
        trials.push_back(run_trial(mode, cfg));
    }

    StatsSummary stats = compute_stats(trials);

    std::cout << "{"
              << "\"policy\": \"" << mode << "\","
              << "\"trials\": " << cfg.trials << ","
              << "\"total_bins\": " << stats.total_bins << ","
              << "\"median_mops\": " << std::fixed << std::setprecision(2) << stats.median_mops << ","
              << "\"stddev_mops\": " << stats.stddev_mops << ","
              << "\"median_ns_op\": " << std::setprecision(1) << stats.median_ns_op << ","
              << "\"peak_rss_kb\": " << stats.median_rss_kb << ","
              << "\"internal_frag_pct\": " << std::setprecision(1) << stats.internal_frag_pct
              << "}" << std::endl;

    return 0;
}
