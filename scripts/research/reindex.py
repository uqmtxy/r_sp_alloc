#!/usr/bin/env python3
"""Deterministically index repository source files and symbols into context/CODE_INDEX.md."""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_PATH = ROOT / "context" / "CODE_INDEX.md"

SKIP_DIRS = {".git", ".venv", "onnxruntime", "__pycache__", "figures", ".pytest_cache"}
SRC_EXTS = {".cpp", ".hpp", ".h", ".c", ".py"}

CPP_SYMBOL_RE = re.compile(
    r"^\s*(?:template\s*<[^>]*>\s*)?(?:class|struct|namespace)\s+([A-Za-z_][A-Za-z0-9_]*)\b"
    r"|^\s*(?:static\s+|inline\s+|explicit\s+|virtual\s+)*(?:[\w:<>~*&]+\s+)+([A-Za-z_][A-Za-z0-9_]*)\s*\([^;{}]*\)\s*(?:const)?\s*\{",
    re.MULTILINE,
)
PY_SYMBOL_RE = re.compile(r"^(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)\b", re.MULTILINE)


def classify_file(rel: str) -> str:
    if rel.startswith("first_steps/bench/utilization/"):
        return "ACTIVE FRONTIER (Utilization & Bounded Retention)"
    if rel.startswith("scripts/research/") or rel.startswith(".agents/"):
        return "RESEARCH INFRASTRUCTURE & AGENT OS"
    if rel.startswith("assignment/"):
        return "ASSIGNMENT DELIVERABLES (Synced Nov 19)"
    if rel.startswith("first_steps/paper/"):
        return "STALE MANUSCRIPT ASSETS (Oct 15/19 Draft)"
    return "ARCHIVED / HISTORICAL PROTOTYPES & BASELINES"


def extract_symbols(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    syms: list[str] = []
    if path.suffix == ".py":
        for m in PY_SYMBOL_RE.finditer(text):
            syms.append(m.group(1))
    else:
        for m in CPP_SYMBOL_RE.finditer(text):
            name = m.group(1) or m.group(2)
            if name and name not in {"if", "for", "while", "switch", "catch", "return"}:
                syms.append(name)
    # Deduplicate preserving order
    seen: set[str] = set()
    uniq = []
    for s in syms:
        if s not in seen:
            seen.add(s)
            uniq.append(s)
    return uniq[:12]


def gather_sources() -> dict[str, list[tuple[str, int, list[str]]]]:
    buckets: dict[str, list[tuple[str, int, list[str]]]] = {
        "ACTIVE FRONTIER (Utilization & Bounded Retention)": [],
        "RESEARCH INFRASTRUCTURE & AGENT OS": [],
        "ASSIGNMENT DELIVERABLES (Synced Nov 19)": [],
        "STALE MANUSCRIPT ASSETS (Oct 15/19 Draft)": [],
        "ARCHIVED / HISTORICAL PROTOTYPES & BASELINES": [],
    }
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or path.suffix not in SRC_EXTS:
            continue
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        rel = path.relative_to(ROOT).as_posix()
        lines = len(path.read_text(encoding="utf-8", errors="ignore").splitlines())
        syms = extract_symbols(path)
        buckets[classify_file(rel)].append((rel, lines, syms))
    return buckets


def render_markdown() -> str:
    buckets = gather_sources()
    total_files = sum(len(v) for v in buckets.values())
    total_loc = sum(item[1] for v in buckets.values() for item in v)
    out = [
        "# Codebase Index (`r_sp_alloc`)",
        "",
        "<!-- AUTO-GENERATED by scripts/research/reindex.py — do not hand-edit. -->",
        "",
        f"Indexed **{total_files}** source files (**{total_loc:,}** lines of C/C++/Python), excluding third-party `onnxruntime/`, `.venv/`, and binaries.",
        "",
    ]
    for group, items in buckets.items():
        if not items:
            continue
        out.append(f"## {group} ({len(items)} files)")
        out.append("")
        out.append("| File | LOC | Key Symbols |")
        out.append("|---|---:|---|")
        for rel, lines, syms in items:
            sym_str = ", ".join(f"`{s}`" for s in syms) if syms else "—"
            out.append(f"| [{rel}](../{rel}) | {lines} | {sym_str} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description="Index r_sp_alloc codebase into context/CODE_INDEX.md")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if context/CODE_INDEX.md is stale")
    args = parser.parse_args()

    rendered = render_markdown()
    if args.check:
        if not OUT_PATH.exists():
            print(f"FAIL: missing {OUT_PATH.relative_to(ROOT)}", file=sys.stderr)
            return 1
        current = OUT_PATH.read_text(encoding="utf-8")
        if current != rendered:
            print(f"FAIL: {OUT_PATH.relative_to(ROOT)} is stale; run `python3 scripts/research/reindex.py`", file=sys.stderr)
            return 1
        print("OK: context/CODE_INDEX.md is up to date")
        return 0

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
